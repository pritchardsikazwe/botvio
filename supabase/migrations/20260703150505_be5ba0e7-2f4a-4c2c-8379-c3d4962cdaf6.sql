## The Botvio XAUUSD Entry Model — Step by Step

### Step 1 · Top-Down Bias (Daily & H4)
- Mark the previous day's high (PDH) and low (PDL).
- Mark the previous week's high and low.
- Identify the H4 structure: is price making HH/HL or LH/LL?
- Note the last H4 BOS or CHoCH — this defines your directional bias for the day.

### Step 2 · H1 Point of Interest (POI)
- Draw the last H1 bullish order block below current price (in a bullish bias) or the last bearish OB above (in a bearish bias).
- Highlight any unmitigated H1 fair value gaps in the direction of your bias.
- Combine OB + FVG for the highest-probability POI ("stacked confluence").

### Step 3 · Liquidity Sweep Confirmation
- Wait for price to raid a nearby liquidity pool: PDH/PDL, Asian range extreme, or a well-defined equal high/low.
- The sweep must be a **wick + close back inside the range**, not a full-body break.

### Step 4 · M15 Entry Trigger
- On the M15 chart, wait for a Change of Character back in the direction of your H4 bias.
- Enter on the M15 order block or FVG created by the CHoCH candle.
- Place stop loss **1 ATR beyond the liquidity sweep wick**.
- First target: nearest opposing liquidity (typically 1R–1.5R).
- Runner target: previous session high/low or major FVG (2R–5R).

### Step 5 · Trade Management
- Move stop to breakeven at +1R.
- Scale out 50% at 2R, trail the remainder using the M15 swing lows/highs.
- Close all positions 15 minutes before major red-folder news.

