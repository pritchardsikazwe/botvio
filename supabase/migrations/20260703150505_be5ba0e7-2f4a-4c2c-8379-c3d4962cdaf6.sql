## The Smart Money Framework (SMC) in One Page

Smart Money Concepts is a modern trading methodology inspired by the Wyckoff method, ICT (Inner Circle Trader) teachings, and institutional order-flow theory. Instead of relying on lagging indicators, SMC focuses on **price structure**, **liquidity**, and **imbalance**.

### 1. Market Structure
- **Bullish structure:** consecutive higher highs (HH) and higher lows (HL).
- **Bearish structure:** consecutive lower highs (LH) and lower lows (LL).
- A **Break of Structure (BOS)** confirms trend continuation.
- A **Change of Character (CHoCH)** is the first signal that the trend may be flipping.

### 2. Liquidity
Liquidity is simply resting stop-loss orders — the fuel institutions need to fill their positions. It pools:
- Above swing highs (buy stops)
- Below swing lows (sell stops)
- Around round numbers ($3,000, $3,100, $3,200)
- At session opens (Asian range highs/lows, London Open, NY Open)

Institutions **sweep** this liquidity before reversing. Watching for these sweeps is the core of the Botvio XAUUSD edge.

### 3. Order Blocks (OB)
An order block is the **last opposing candle** before an impulsive move. When price returns to that candle, institutions defend the level, often creating a reversal. Bullish order blocks act as demand; bearish order blocks act as supply.

### 4. Fair Value Gaps (FVG) / Imbalances
When price prints a three-candle sequence where the middle candle leaves a gap between the wick of candle 1 and candle 3, that gap is an **imbalance**. Price tends to return to fill (mitigate) this inefficiency. FVGs are excellent low-risk entry zones, especially when they align with an order block.

